package ro.astrosite.engine.scoring;

/** Life areas a question or a day score can refer to. */
public enum Category {
    LOVE,           // dating, meeting people, relationships, social life
    CAREER,         // work, interviews, starting projects, negotiations
    MONEY,          // purchases, contracts, investments (general, non-advisory)
    TRAVEL,         // trips, moving around
    COMMUNICATION,  // conversations, emails, signing, publishing
    HOME,           // family, moving house, domestic matters
    WELLBEING,      // rest, self-care, energy (never medical advice)
    GENERAL
}
